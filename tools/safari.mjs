// Tema — the Safari build.
//
//   node tools/safari.mjs           build the Mac app and install it (/Applications)
//   node tools/safari.mjs build     build it only, into safari/build/
//   node tools/safari.mjs stage     write the Safari web extension only, into
//                                   safari/build/web/ (the tests use this)
//
// Safari takes a web extension inside a Mac app: safari/Tema.xcodeproj is
// that app, and its extension target copies safari/build/web/ in at build
// time. There is one copy of the extension, this repository; the Safari one
// is generated from it:
//
//   - the same files the Chrome zip ships (tools/package.mjs), plus
//   - src/safari/<site>.js per site: that site's stylesheets as text, which
//     the engine adopts as a constructed stylesheet (core.js, "Safari").
//     Safari runs content scripts but hasn't reliably applied a manifest's
//     CSS to freshly loaded pages (found porting Apollo, 2026-10), so the
//     Safari manifest lists no CSS at all and the stylesheet comes in with
//     the scripts: one path, the one tools/tests/safari.mjs exercises.
//
// Signing: with an "Apple Development" certificate in the keychain the app is
// signed with its team, which Safari keeps enabled across restarts. Without
// one it is signed ad hoc ("Sign to Run Locally"), which Safari only loads
// while Develop → Developer Settings → "Allow unsigned extensions" is on.
// TEAM_ID=… overrides the team.

import { execFile, spawn } from "node:child_process";
import { promisify } from "node:util";
import { mkdir, rm, cp, readFile, writeFile, access } from "node:fs/promises";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadThemes } from "./build.mjs";
import { packageFiles } from "./package.mjs";

const run = promisify(execFile);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SAFARI = join(ROOT, "safari");
export const STAGE = join(SAFARI, "build", "web");
const APP_NAME = "Tema.app";
const BUNDLE_ID = "com.kurisu.Tema";

/** The site a content-script entry is for, by its matches. */
function siteFor(entry, sites) {
  const site = sites.find((s) => s.matches.every((m) => entry.matches.includes(m)));
  if (!site) throw new Error("no site matches content script " + entry.matches.join(" "));
  return site;
}

/** Write the Safari web extension to `dest` (default safari/build/web). */
export async function stage(dest = STAGE) {
  const { sites } = await loadThemes();
  const files = await packageFiles();
  await rm(dest, { recursive: true, force: true });
  for (const f of files) {
    await mkdir(dirname(join(dest, f)), { recursive: true });
    await cp(join(ROOT, f), join(dest, f));
  }

  const manifest = JSON.parse(await readFile(join(ROOT, "manifest.json"), "utf8"));
  await mkdir(join(dest, "src/safari"), { recursive: true });
  for (const entry of manifest.content_scripts) {
    const site = siteFor(entry, sites);
    let css = "";
    for (const f of entry.css || []) css += `/* ${f} */\n` + (await readFile(join(ROOT, f), "utf8")) + "\n";
    const name = `src/safari/${site.id}.js`;
    await writeFile(join(dest, name),
      `// Generated by tools/safari.mjs from ${(entry.css || []).join(", ")}. Do not edit.\n` +
      `// ${site.name}'s stylesheets, adopted by src/content/core.js (see "Safari" there).\n` +
      `globalThis.TemaSafariCss = ${JSON.stringify(css)};\n`, "utf8");
    entry.js = [name, ...entry.js];
    delete entry.css;
  }
  await writeFile(join(dest, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");
  return { dest, version: manifest.version, files: files.length + manifest.content_scripts.length };
}

/** The Apple Development team to sign with, or null for ad hoc. */
async function signingTeam() {
  if (process.env.TEAM_ID) return process.env.TEAM_ID;
  try {
    const { stdout } = await run("security", ["find-identity", "-v", "-p", "codesigning"]);
    if (!/"Apple Development/.test(stdout)) return null;
    const { stdout: pem } = await run("security", ["find-certificate", "-c", "Apple Development", "-p"]);
    const subject = await new Promise((resolveSubject, reject) => {
      const p = spawn("openssl", ["x509", "-noout", "-subject"]);
      let out = "";
      p.stdout.on("data", (d) => { out += d; });
      p.on("error", reject);
      p.on("close", () => resolveSubject(out));
      p.stdin.end(pem);
    });
    const m = /OU ?= ?([A-Z0-9]{10})/.exec(subject);
    return m ? m[1] : null;
  } catch {
    return null;
  }
}

const DERIVED = join(SAFARI, "build", "DerivedData");
const BUILT = join(DERIVED, "Build/Products/Release", APP_NAME);

/** Build safari/Tema.xcodeproj; returns the built app's path. */
export async function build() {
  const { version } = await stage();
  const team = await signingTeam();
  const sign = team
    ? ["CODE_SIGN_STYLE=Manual", "CODE_SIGN_IDENTITY=Apple Development", `DEVELOPMENT_TEAM=${team}`, "PROVISIONING_PROFILE_SPECIFIER="]
    : ["CODE_SIGN_STYLE=Manual", "CODE_SIGN_IDENTITY=-", "DEVELOPMENT_TEAM="];
  console.log(team ? `Signing with Apple Development (team ${team})` :
    "No Apple Development certificate: signing ad hoc (Safari needs \"Allow unsigned extensions\")");

  // The extension target's copy phase rewrites the web files inside the signed
  // appex, and an incremental build that changed only web files can skip the
  // re-sign, which Safari then rejects ("Disabling and blocking extension",
  // found with Apollo). Building the products afresh always signs.
  await rm(join(DERIVED, "Build/Products"), { recursive: true, force: true });
  console.log(`Building Tema for Safari ${version}…`);
  await new Promise((resolveBuild, reject) => {
    const p = spawn("xcodebuild", [
      "-quiet",
      "-project", join(SAFARI, "Tema.xcodeproj"),
      "-scheme", "Tema",
      "-configuration", "Release",
      "-destination", "generic/platform=macOS",
      "-derivedDataPath", DERIVED,
      `MARKETING_VERSION=${version}`,
      ...sign,
      "build",
    ], { stdio: "inherit" });
    p.on("error", reject);
    p.on("close", (code) => (code === 0 ? resolveBuild() : reject(new Error(`xcodebuild exited ${code}`))));
  });
  await run("codesign", ["--verify", "--deep", "--strict", BUILT]).catch((err) => {
    throw new Error("the built app's signature doesn't verify, so it isn't installed\n" + (err.stderr || err.message));
  });
  console.log(`Built ${BUILT}`);
  return BUILT;
}

const LSREGISTER = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister";

/** Build, then install into /Applications (or ~/Applications) and register with Safari. */
export async function install() {
  const built = await build();
  let destDir = "/Applications";
  try { await access(destDir, 2 /* W_OK */); } catch { destDir = join(process.env.HOME, "Applications"); }
  await mkdir(destDir, { recursive: true });
  const dest = join(destDir, APP_NAME);

  // Stage next to the build and swap in with one rename, so Safari never sees
  // a half-copied bundle (whose signature wouldn't verify).
  const staged = join(SAFARI, "build", "stage", APP_NAME);
  await rm(dirname(staged), { recursive: true, force: true });
  await mkdir(dirname(staged), { recursive: true });
  await run("ditto", [built, staged]);
  // "tell … to quit" alone would launch the app to quit it.
  await run("osascript", ["-e", `if application id "${BUNDLE_ID}" is running then tell application id "${BUNDLE_ID}" to quit`]).catch(() => {});
  await rm(dest, { recursive: true, force: true });
  await run("mv", [staged, dest]);

  // Xcode registers every app it builds, so the copy in DerivedData would show
  // in Safari as a second Tema. Keep only the installed one, and re-add its
  // extension so Safari judges this build afresh.
  const appex = (app) => join(app, "Contents/PlugIns/Tema Extension.appex");
  await run("pluginkit", ["-r", appex(built)]).catch(() => {});
  await run(LSREGISTER, ["-u", built]).catch(() => {});
  await run(LSREGISTER, ["-f", dest]);
  await run("pluginkit", ["-r", appex(dest)]).catch(() => {});
  await run("pluginkit", ["-a", appex(dest)]);
  // Opened once, in the background, so Safari lists the extension.
  await run("open", ["-g", dest]);
  console.log(`Installed ${dest}`);
  console.log("In Safari: Settings → Extensions → tick Tema, then open Tema's toolbar button and tick your sites.");
  return dest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const cmd = process.argv[2] || "install";
  if (cmd === "stage") {
    const { dest, files } = await stage();
    console.log(`Staged the Safari web extension in ${dest} (${files} files)`);
  } else if (cmd === "build") {
    await build();
  } else if (cmd === "install") {
    await install();
  } else {
    console.error("usage: node tools/safari.mjs [install | build | stage]");
    process.exit(2);
  }
}
