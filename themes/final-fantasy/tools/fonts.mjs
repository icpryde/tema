// Tema / Final Fantasy — embed the two pixel fonts.
//
//   node themes/final-fantasy/tools/fonts.mjs
//
// Writes assets/fonts.css with both faces inlined as woff2 data URIs (8KB of
// font, ~11KB of CSS). Inlined rather than linked: a url() in content-script
// CSS can resolve against the PAGE (Chrome once fetched claude.ai's app
// shell as a "font" that way), and the absolute alternative hardcodes
// chrome-extension://, which Safari does not speak. A data URI needs neither.
// Some pages refuse data: fonts outright (claude.ai's font-src, 2026-10), so
// theme.json also lists the files under "fonts" and Tema's engine adds them
// through the FontFace API, which no page policy can block. Whichever copy
// the page accepts first draws the text.
//
// Both faces are SIL Open Font License 1.1; assets/fonts/OFL.txt ships with them.
//
//   Press Start 2P — the chunky NES face, with real lowercase. Titles, and
//                    prose (Silkscreen has no true lowercase: its lowercase
//                    codepoints are the capitals, so prose in it SHOUTS).
//   Silkscreen     — smaller and tighter; holds up at UI sizes, so it carries
//                    sidebar rows, buttons and labels.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const THEME = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const FACES = [
  ["FF Press Start", "assets/fonts/PressStart2P.woff2"],
  ["FF Silkscreen", "assets/fonts/Silkscreen.woff2"],
];

let css = `/* GENERATED by themes/final-fantasy/tools/fonts.mjs — do not edit by hand.
   Press Start 2P (c) 2012 CodeMan38 and Silkscreen (c) 2001 Jason Kottke,
   both SIL Open Font License 1.1 (assets/fonts/OFL.txt). */
`;
for (const [family, file] of FACES) {
  const b64 = (await readFile(resolve(THEME, file))).toString("base64");
  css += `
@font-face {
  font-family: "${family}";
  src: url("data:font/woff2;base64,${b64}") format("woff2");
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}
`;
}

await writeFile(resolve(THEME, "assets/fonts.css"), css, "utf8");
console.log(`wrote assets/fonts.css (${(css.length / 1024).toFixed(1)}KB)`);
